/**
 * Embeds drizzle-kit's SQL into a TypeScript module, because a `bun build --compile`
 * binary has no migrations folder to read at runtime. Run by `bun run db:generate`.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(import.meta.dir, '../drizzle');
const migrations = readdirSync(dir)
  .filter((f) => f.endsWith('.sql'))
  .sort()
  .map((f) => ({ tag: f.replace(/\.sql$/, ''), sql: readFileSync(join(dir, f), 'utf8') }));

writeFileSync(
  join(import.meta.dir, '../src/db/migrations.gen.ts'),
  `// Generated by scripts/embed-migrations.ts. Do not edit.\nexport const migrations = ${JSON.stringify(migrations, null, 2)};\n`,
);
console.log(`Embedded ${migrations.length} migration(s)`);
