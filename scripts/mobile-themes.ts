/** Regenerates apps/mobile/src/theme.gen.ts from the web app's tokens.css, so the themes match. */
import { readFileSync, writeFileSync } from 'node:fs';

const KEYS = [
  'bg',
  'panel',
  'panel-border',
  'line-mid',
  'ink',
  'muted',
  'placeholder',
  'accent',
  'bubble-sirius',
  'input',
  'on-ink',
  'sirius-1',
  'sirius-2',
] as const;
const css = readFileSync('packages/ui/src/styles/tokens.css', 'utf8');
const blocks = [...css.matchAll(/:root(?:\[data-theme="([a-z-]+)"\])?\s*\{([^}]*)\}/g)];
const read = (body: string) =>
  Object.fromEntries(
    [...body.matchAll(/--([a-z0-9-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2]?.trim()]),
  );
const base = read(blocks.find((b) => !b[1])?.[2] ?? '');
const camel = (k: string) => k.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
const themes: Record<string, Record<string, string>> = {};
for (const [, id = 'paper', body = ''] of blocks) {
  const vars = { ...base, ...read(body) };
  themes[id] = Object.fromEntries(
    KEYS.map((k) => {
      if (!vars[k]) throw new Error(`theme ${id} has no --${k}`);
      return [camel(k), vars[k] as string];
    }),
  );
}
writeFileSync(
  'apps/mobile/src/theme.gen.ts',
  `// Generated by scripts/mobile-themes.ts from packages/ui/src/styles/tokens.css. Do not edit.\nexport const THEME_COLORS = ${JSON.stringify(themes, null, 2)} as const;\n`,
);
console.log(`wrote ${Object.keys(themes).length} themes`);
