/** Regenerates packages/ui/src/avatar/orbit.gen.ts from the layered logo SVG.
 * The SVG itself comes from `uv run scripts/logo_to_layers.py logo.png sirius.svg`. */
import { readFileSync, writeFileSync } from 'node:fs';

const svg = readFileSync('docs/design/sirius-logo/sirius.svg', 'utf8');
const path = (id: string) => {
  const d = svg.match(new RegExp(`id="${id}"[^>]*\\sd="([^"]+)"`))?.[1];
  if (!d) throw new Error(`no path #${id} in sirius.svg`);
  return d;
};
const attr = (id: string, name: string) =>
  (svg.match(new RegExp(`id="${id}"[^>]*${name}="([^"]+)"`))?.[1] ?? '').split(' ').map(Number);
const out = {
  head: path('head'),
  earBack: path('ear-back'),
  eye: path('eye'),
  ring: path('ring'),
  star: path('star'),
  ringCentre: attr('ring', 'data-center'),
  starCentre: attr('star', 'data-center'),
  wolfPivot: attr('wolf', 'data-pivot'),
};
writeFileSync(
  'packages/ui/src/avatar/orbit.gen.ts',
  `// Generated by scripts/orbit-paths.ts from docs/design/sirius-logo/sirius.svg. Do not edit.\nexport const ORBIT = ${JSON.stringify(out, null, 2)} as const;\n`,
);
