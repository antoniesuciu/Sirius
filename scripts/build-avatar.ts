/**
 * Optimises docs/design/sirius.svg into the string the avatar component inlines.
 *
 * The classes and the clip-path id are the animation contract (spec section 0), so
 * every plugin that could rename, merge or drop them is off. The source is already
 * tight at one decimal, so the saving comes from rounding to whole units: the avatar
 * renders at 76 px in a 512-unit viewBox, so that error is well under a tenth of a pixel.
 * Run with `bun run scripts/build-avatar.ts` after changing the source SVG.
 */
import { gzipSync } from 'node:zlib';
import { optimize } from 'svgo';

const source = await Bun.file('docs/design/sirius.svg').text();
const { data } = optimize(source, {
  multipass: true,
  floatPrecision: 0,
  plugins: [
    {
      name: 'preset-default',
      params: {
        overrides: {
          cleanupIds: false,
          collapseGroups: false,
          mergePaths: false,
          removeUnknownsAndDefaults: false,
        },
      },
    },
  ],
});

for (const needed of ['class="eyes"', 'class="iris"', 'class="line"', 'id="sirius-eyes"']) {
  if (!data.includes(needed)) throw new Error(`Optimised SVG lost ${needed}`);
}

const out = `// Generated by scripts/build-avatar.ts. Do not edit.\nexport const siriusSvg = ${JSON.stringify(data)};\n`;
await Bun.write('packages/ui/src/avatar/sirius.gen.ts', out);
console.log(`sirius.svg ${source.length} → ${data.length} bytes, ${gzipSync(data).length} gzipped`);
